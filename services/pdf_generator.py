"""Professional PDF report generator using ReportLab."""
from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT, TA_CENTER, TA_JUSTIFY
from reportlab.lib.pagesizes import LETTER
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Image,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
    KeepTogether,
    HRFlowable,
)

import config


BRAND_PRIMARY = colors.HexColor("#4F46E5")
BRAND_ACCENT = colors.HexColor("#7C3AED")
BRAND_DARK = colors.HexColor("#1E1B4B")
BRAND_LIGHT = colors.HexColor("#EEF2FF")
TEXT_MUTED = colors.HexColor("#64748B")
BORDER = colors.HexColor("#E2E8F0")


def _styles() -> dict:
    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle(
            "TitleX", parent=base["Title"], fontSize=26, textColor=BRAND_DARK,
            spaceAfter=6, alignment=TA_LEFT, fontName="Helvetica-Bold",
        ),
        "subtitle": ParagraphStyle(
            "SubtitleX", parent=base["Normal"], fontSize=11, textColor=TEXT_MUTED,
            spaceAfter=20, alignment=TA_LEFT,
        ),
        "h1": ParagraphStyle(
            "H1X", parent=base["Heading1"], fontSize=17, textColor=BRAND_PRIMARY,
            spaceBefore=14, spaceAfter=8, fontName="Helvetica-Bold",
        ),
        "h2": ParagraphStyle(
            "H2X", parent=base["Heading2"], fontSize=13, textColor=BRAND_DARK,
            spaceBefore=10, spaceAfter=6, fontName="Helvetica-Bold",
        ),
        "body": ParagraphStyle(
            "BodyX", parent=base["Normal"], fontSize=10.5, leading=15,
            alignment=TA_JUSTIFY, textColor=colors.HexColor("#1F2937"),
        ),
        "bullet": ParagraphStyle(
            "BulX", parent=base["Normal"], fontSize=10.5, leading=15,
            leftIndent=16, bulletIndent=4, textColor=colors.HexColor("#1F2937"),
        ),
        "meta": ParagraphStyle(
            "MetaX", parent=base["Normal"], fontSize=9, textColor=TEXT_MUTED,
        ),
        "tag": ParagraphStyle(
            "TagX", parent=base["Normal"], fontSize=8.5, textColor=colors.white,
            alignment=TA_CENTER, fontName="Helvetica-Bold",
        ),
        "quote": ParagraphStyle(
            "QuoteX", parent=base["Normal"], fontSize=10, leading=14,
            leftIndent=14, textColor=colors.HexColor("#334155"),
            borderColor=BRAND_PRIMARY, borderWidth=0, borderPadding=0,
        ),
        "footer": ParagraphStyle(
            "FootX", parent=base["Normal"], fontSize=8, textColor=TEXT_MUTED,
            alignment=TA_CENTER,
        ),
    }
    return styles


def _brand_header(canvas, doc):
    canvas.saveState()
    w, h = LETTER
    # Colored top strip
    canvas.setFillColor(BRAND_PRIMARY)
    canvas.rect(0, h - 0.35 * inch, w, 0.35 * inch, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 11)
    canvas.drawString(0.5 * inch, h - 0.24 * inch, "AI Email Intelligence Platform")
    canvas.setFont("Helvetica", 9)
    canvas.drawRightString(w - 0.5 * inch, h - 0.24 * inch,
                            datetime.utcnow().strftime("%B %d, %Y"))
    # Footer
    canvas.setFillColor(TEXT_MUTED)
    canvas.setFont("Helvetica", 8)
    canvas.drawCentredString(w / 2, 0.35 * inch,
                              f"Page {doc.page}  •  Generated by AI Email Intelligence Platform")
    canvas.restoreState()


def _escape(text: str) -> str:
    if text is None:
        return ""
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _sentiment_color(sentiment: str) -> colors.Color:
    m = {
        "positive": colors.HexColor("#10B981"),
        "neutral": colors.HexColor("#64748B"),
        "negative": colors.HexColor("#EF4444"),
        "urgent": colors.HexColor("#F59E0B"),
        "mixed": colors.HexColor("#8B5CF6"),
    }
    return m.get((sentiment or "").lower(), colors.HexColor("#64748B"))


def _metric_row(items: list[tuple[str, str]]) -> Table:
    """Build a horizontal row of KPI tiles."""
    cells = []
    for label, value in items:
        cell = Table(
            [[Paragraph(f"<b>{_escape(value)}</b>",
                        ParagraphStyle("v", fontSize=18, textColor=BRAND_PRIMARY,
                                        alignment=TA_CENTER, fontName="Helvetica-Bold"))],
             [Paragraph(_escape(label),
                        ParagraphStyle("l", fontSize=9, textColor=TEXT_MUTED, alignment=TA_CENTER))]],
            colWidths=[1.6 * inch],
        )
        cell.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), BRAND_LIGHT),
            ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
            ("PADDING", (0, 0), (-1, -1), 10),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(cell)
    # Wrap in a table for horizontal layout
    row = Table([cells], colWidths=[1.75 * inch] * len(cells))
    row.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
    ]))
    return row


def _tag(text: str, color: colors.Color) -> Table:
    t = Table([[Paragraph(_escape(text.upper()),
                          ParagraphStyle("tg", fontSize=8, textColor=colors.white,
                                          alignment=TA_CENTER, fontName="Helvetica-Bold"))]],
              colWidths=[1.0 * inch])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), color),
        ("PADDING", (0, 0), (-1, -1), 4),
        ("BOX", (0, 0), (-1, -1), 0, color),
    ]))
    return t


