def generate_email_report(email: dict, analysis: dict, output_path: Path | None = None) -> Path:
    """Single-email deep-dive PDF."""
    st = _styles()
    if output_path is None:
        output_path = config.REPORTS_DIR / f"email_{email['id']}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
    doc = SimpleDocTemplate(
        str(output_path), pagesize=LETTER,
        topMargin=0.7 * inch, bottomMargin=0.7 * inch,
        leftMargin=0.6 * inch, rightMargin=0.6 * inch,
    )
    story = []
    story.append(Paragraph("Email Intelligence Report", st["title"]))
    story.append(Paragraph(
        f"Deep analysis of a single email • Generated {datetime.utcnow().strftime('%b %d, %Y at %H:%M UTC')}",
        st["subtitle"],
    ))
    story.append(HRFlowable(width="100%", thickness=1, color=BORDER, spaceBefore=0, spaceAfter=14))

    # Metadata card
    meta_table = Table([
        ["Subject", email.get("subject", "")],
        ["From", f"{email.get('sender', '')} <{email.get('sender_email', '')}>"],
        ["To", email.get("recipient", "")],
        ["Date", email.get("date", "")[:19].replace("T", " ")],
        ["Category", (email.get("category") or "uncategorized").title()],
        ["Priority", f"{email.get('priority', 0)}/10"],
    ], colWidths=[1.1 * inch, 5.4 * inch])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), BRAND_LIGHT),
        ("TEXTCOLOR", (0, 0), (0, -1), BRAND_DARK),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("PADDING", (0, 0), (-1, -1), 8),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 16))

    # AI summary section
    story.append(Paragraph("Executive Summary", st["h1"]))
    story.append(Paragraph(_escape(analysis.get("summary", "No summary available.")), st["body"]))
    story.append(Spacer(1, 10))

    # Sentiment badge
    sentiment = analysis.get("sentiment", "neutral")
    story.append(Paragraph(
        f"<b>Sentiment:</b> <font color='{_sentiment_color(sentiment).hexval()}'>{_escape(sentiment.upper())}</font>",
        st["body"],
    ))
    story.append(Spacer(1, 10))

    # Key points
    kp = analysis.get("key_points") or []
    if kp:
        story.append(Paragraph("Key Points", st["h2"]))
        for p in kp:
            story.append(Paragraph(f"• {_escape(p)}", st["bullet"]))
        story.append(Spacer(1, 8))

    # Action items
    ai = analysis.get("action_items") or []
    if ai:
        story.append(Paragraph("Action Items", st["h2"]))
        for a in ai:
            story.append(Paragraph(f"→ {_escape(a)}", st["bullet"]))
        story.append(Spacer(1, 8))

    # Entities
    ents = analysis.get("entities") or []
    if ents:
        story.append(Paragraph("Key Entities Mentioned", st["h2"]))
        story.append(Paragraph(_escape(", ".join(ents)), st["body"]))
        story.append(Spacer(1, 8))

    # Suggested response
    meta = analysis.get("metadata") or {}
    if isinstance(meta, dict) and meta.get("suggested_response"):
        story.append(Paragraph("Suggested Response", st["h2"]))
        story.append(Paragraph(_escape(meta["suggested_response"]), st["quote"]))
        story.append(Spacer(1, 10))

    # Original body
    story.append(PageBreak())
    story.append(Paragraph("Original Email Body", st["h1"]))
    body = email.get("body_text") or email.get("snippet") or ""
    for para in body.split("\n\n"):
        if para.strip():
            story.append(Paragraph(_escape(para).replace("\n", "<br/>"), st["body"]))
            story.append(Spacer(1, 6))

    doc.build(story, onFirstPage=_brand_header, onLaterPages=_brand_header)
    return output_path


def generate_thread_report(thread_id: str, emails: list[dict], analysis: dict, output_path: Path | None = None) -> Path:
    """Thread conversation analysis PDF."""
    st = _styles()
    if output_path is None:
        output_path = config.REPORTS_DIR / f"thread_{thread_id[:20]}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
    doc = SimpleDocTemplate(
        str(output_path), pagesize=LETTER,
        topMargin=0.7 * inch, bottomMargin=0.7 * inch,
        leftMargin=0.6 * inch, rightMargin=0.6 * inch,
    )
    story = []
    subject = emails[0].get("subject", "Thread") if emails else "Thread"
    story.append(Paragraph("Email Thread Analysis", st["title"]))
    story.append(Paragraph(
        f"Conversation: <b>{_escape(subject)}</b> • {len(emails)} messages",
        st["subtitle"],
    ))
    story.append(HRFlowable(width="100%", thickness=1, color=BORDER, spaceBefore=0, spaceAfter=14))

    # Metric tiles
    participants = {e.get("sender_email") for e in emails if e.get("sender_email")}
    duration_days = "-"
    if emails:
        try:
            first = min((e.get("date") or "" for e in emails if e.get("date")))
            last = max((e.get("date") or "" for e in emails if e.get("date")))
            first_dt = datetime.fromisoformat(first.replace("Z", "+00:00"))
            last_dt = datetime.fromisoformat(last.replace("Z", "+00:00"))
            duration_days = f"{(last_dt - first_dt).days}"
        except Exception:
            pass

    story.append(_metric_row([
        ("Messages", str(len(emails))),
        ("Participants", str(len(participants))),
        ("Days Span", duration_days),
        ("Sentiment", (analysis.get("sentiment") or "n/a").title()),
    ]))
    story.append(Spacer(1, 16))

    # Executive summary
    story.append(Paragraph("What's Happened So Far", st["h1"]))
    story.append(Paragraph(_escape(analysis.get("summary", "")), st["body"]))
    story.append(Spacer(1, 10))

    meta = analysis.get("metadata") or {}
    if isinstance(meta, dict) and meta.get("timeline"):
        story.append(Paragraph("Timeline", st["h2"]))
        story.append(Paragraph(_escape(meta["timeline"]), st["body"]))
        story.append(Spacer(1, 8))

    # Participants table — all senders, emails, message counts
    story.append(Paragraph("Participants", st["h2"]))
    from collections import Counter
    p_counter: Counter = Counter()
    p_names: dict = {}
    for e in emails:
        se = e.get("sender_email") or ""
        p_counter[se] += 1
        if se and se not in p_names:
            p_names[se] = e.get("sender") or se
    participant_rows = [["Name", "Email", "Messages"]]
    for se, c in p_counter.most_common():
        participant_rows.append([p_names.get(se, se), se, str(c)])
    p_tbl = Table(participant_rows, colWidths=[2.0 * inch, 3.2 * inch, 1.0 * inch])
    p_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))
    story.append(p_tbl)
    story.append(Spacer(1, 12))

    # Message index table — subject / from / time
    story.append(Paragraph("Messages in this Thread", st["h2"]))
    idx_rows = [["#", "Date", "From", "Subject"]]
    for i, e in enumerate(emails, 1):
        idx_rows.append([
            str(i),
            (e.get("date") or "")[:16].replace("T", " "),
            (e.get("sender") or "")[:22],
            (e.get("subject") or "")[:44],
        ])
    idx_tbl = Table(idx_rows, colWidths=[0.35 * inch, 1.35 * inch, 1.65 * inch, 2.85 * inch])
    idx_tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_ACCENT),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("PADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))
    story.append(idx_tbl)
    story.append(Spacer(1, 12))

    kp = analysis.get("key_points") or []
    if kp:
        story.append(Paragraph("Key Points", st["h2"]))
        for p in kp:
            story.append(Paragraph(f"• {_escape(p)}", st["bullet"]))
        story.append(Spacer(1, 8))

    if isinstance(meta, dict):
        decisions = meta.get("decisions_made") or []
        if decisions:
            story.append(Paragraph("Decisions Made", st["h2"]))
            for d in decisions:
                story.append(Paragraph(f"✓ {_escape(d)}", st["bullet"]))
            story.append(Spacer(1, 8))

        oq = meta.get("open_questions") or []
        if oq:
            story.append(Paragraph("Open Questions", st["h2"]))
            for q in oq:
                story.append(Paragraph(f"? {_escape(q)}", st["bullet"]))
            story.append(Spacer(1, 8))

    ai = analysis.get("action_items") or []
    if ai:
        story.append(Paragraph("Recommended Actions to Take", st["h2"]))
        for a in ai:
            story.append(Paragraph(f"→ {_escape(a)}", st["bullet"]))
        story.append(Spacer(1, 8))

    ents = analysis.get("entities") or []
    if ents:
        story.append(Paragraph("Key Entities", st["h2"]))
        story.append(Paragraph(_escape(", ".join(ents)), st["body"]))
        story.append(Spacer(1, 10))

    # Message timeline
    story.append(PageBreak())
    story.append(Paragraph("Message Timeline", st["h1"]))
    for i, e in enumerate(emails, 1):
        block = []
        block.append(Paragraph(
            f"<b>#{i} • {_escape(e.get('sender', ''))}</b> "
            f"<font color='#94a3b8'>&lt;{_escape(e.get('sender_email', ''))}&gt;</font><br/>"
            f"<font size='8' color='#64748b'>{_escape(e.get('date', '')[:19].replace('T', ' '))}</font>",
            st["body"],
        ))
        block.append(Spacer(1, 4))
        body = (e.get("body_text") or e.get("snippet") or "")[:1500]
        block.append(Paragraph(_escape(body).replace("\n", "<br/>"), st["quote"]))
        block.append(Spacer(1, 8))
        block.append(HRFlowable(width="100%", thickness=0.5, color=BORDER, spaceAfter=6))
        story.append(KeepTogether(block))

    doc.build(story, onFirstPage=_brand_header, onLaterPages=_brand_header)
    return output_path


def generate_digest_report(
    emails: list[dict],
    digest: dict,
    title: str = "Email Digest Report",
    stats: dict | None = None,
    output_path: Path | None = None,
) -> Path:
    """Executive digest across many emails - weekly report style."""
    st = _styles()
    if output_path is None:
        output_path = config.REPORTS_DIR / f"digest_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
    doc = SimpleDocTemplate(
        str(output_path), pagesize=LETTER,
        topMargin=0.7 * inch, bottomMargin=0.7 * inch,
        leftMargin=0.6 * inch, rightMargin=0.6 * inch,
    )
    story = []
    story.append(Paragraph(title, st["title"]))
    story.append(Paragraph(
        f"Executive email intelligence digest • {len(emails)} emails analyzed • "
        f"Generated {datetime.utcnow().strftime('%b %d, %Y at %H:%M UTC')}",
        st["subtitle"],
    ))
    story.append(HRFlowable(width="100%", thickness=1, color=BORDER, spaceBefore=0, spaceAfter=14))

    # Stats
    if stats:
        story.append(_metric_row([
            ("Total Emails", str(stats.get("total", len(emails)))),
            ("Unread", str(stats.get("unread", 0))),
            ("Threads", str(stats.get("threads", 0))),
            ("Analyzed", str(stats.get("analyzed", 0))),
        ]))
        story.append(Spacer(1, 16))

    story.append(Paragraph("Executive Overview", st["h1"]))
    story.append(Paragraph(_escape(digest.get("summary", "")), st["body"]))
    story.append(Spacer(1, 10))

    for section_key, heading in [
        ("themes", "Dominant Themes"),
        ("priorities", "Top Priorities"),
        ("insights", "Insights & Patterns"),
        ("recommended_actions", "Recommended Actions"),
        ("top_correspondents", "Top Correspondents"),
    ]:
        items = digest.get(section_key) or []
        if items:
            story.append(Paragraph(heading, st["h2"]))
            for item in items:
                story.append(Paragraph(f"• {_escape(item)}", st["bullet"]))
            story.append(Spacer(1, 8))

    # Email listing table
    story.append(PageBreak())
    story.append(Paragraph("Analyzed Emails Index", st["h1"]))
    data = [["Date", "From", "Subject", "Category", "Priority"]]
    for e in emails[:60]:
        data.append([
            (e.get("date") or "")[:10],
            (e.get("sender") or "")[:24],
            (e.get("subject") or "")[:40],
            (e.get("category") or "-").title()[:12],
            str(e.get("priority") or "-"),
        ])
    tbl = Table(data, colWidths=[0.9 * inch, 1.5 * inch, 3.2 * inch, 0.9 * inch, 0.6 * inch])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BRAND_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("PADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("INNERGRID", (0, 0), (-1, -1), 0.25, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
    ]))
    story.append(tbl)

    doc.build(story, onFirstPage=_brand_header, onLaterPages=_brand_header)
    return output_path
